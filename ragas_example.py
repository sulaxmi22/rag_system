"""
RAGAS Example Usage
Demonstrates how to evaluate your RAG system using RAGAS
This script shows two approaches:
1. Evaluate pre-collected Q&A pairs (offline evaluation)
2. Evaluate live RAG pipeline results (online evaluation)

- Measure system quality objectively
- Track improvements over time
- Identify specific weaknesses (retrieval vs generation)
- Compare different configurations (models, chunking, etc.)
"""

from ragas_evaluator import RAGASEvaluator, print_evaluation_report
from ingestion import ingestion_pipeline
from gateway import gateway
